-- Migration 011: Transição Líder → Membro (idempotente)
-- ============================================================
DO $$
DECLARE
    v_lider_id INTEGER;
    v_membro_id INTEGER;
BEGIN
    SELECT id_cargo INTO v_lider_id FROM cargos WHERE nome = 'Líder de ministério' AND id_igreja_fk IS NOT NULL LIMIT 1;
    SELECT id_cargo INTO v_membro_id FROM cargos WHERE nome = 'Membro' AND id_igreja_fk IS NOT NULL LIMIT 1;
    IF v_lider_id IS NOT NULL AND v_membro_id IS NOT NULL THEN
        UPDATE membros SET id_cargo_fk = v_membro_id WHERE id_cargo_fk = v_lider_id;
    END IF;
END$$;

